"""
Phase 1: the same pipeline from phase0_extract.py, wrapped as a real
HTTP service instead of a CLI script — so a browser extension (or
anything else) can call it.

Run locally with:
    uvicorn api:app --reload

Then test with:
    curl -F "file=@bol2.pdf" "http://127.0.0.1:8000/extract?mode=groq&target=netchb"

Docs/interactive testing UI (auto-generated by FastAPI):
    http://127.0.0.1:8000/docs

Caching: only the EXTRACTION (Docling + LLM, the slow/expensive part) is
cached, keyed by file hash + mode. Normalization and mapping are cheap and
deterministic, so they re-run on every request. That means changing a
mapping rule, a client answer, or the requested target takes effect
immediately, with no need to clear the cache.
"""

import tempfile
import os

from fastapi import FastAPI, UploadFile, File, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from database import init_db, hash_file_bytes, get_cached_result, save_result

# Reusing the exact functions already validated in Phase 0 — nothing
# about the extraction/normalization/mapping logic changes here.
from phase0_extract import extract_markdown, extract_with_groq, extract_with_gemini
from normalize import normalize_fields
from ace_mapping import map_to_ace_fields
from netchb_mapping import map_to_netchb_fields, netchb_warnings

# Bump this whenever BOL_SCHEMA or the extraction prompts change. Cached
# extractions made under an older version are ignored and re-extracted,
# instead of silently serving data that lacks the new fields.
EXTRACTION_VERSION = 2

app = FastAPI(title="BOL Extraction API")

# Allows the browser extension (a different origin: chrome-extension://...)
# to call this API. Wide open for local development — worth tightening
# before this is ever exposed beyond your own machine.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.on_event("startup")
def on_startup():
    init_db()


@app.get("/health")
def health():
    return {"status": "ok"}


def build_response(fields: dict, target: str) -> dict:
    """Normalize + map the raw extraction. Cheap and deterministic, so it
    runs fresh on every request, cached extraction or not."""
    normalized = normalize_fields(fields)

    result = {"extracted_fields": fields}
    if target in ("ace", "both"):
        result["ace_fields"] = map_to_ace_fields(normalized)
    if target in ("netchb", "both"):
        result["netchb_fields"] = map_to_netchb_fields(normalized)
        result["warnings"] = netchb_warnings(normalized)
    return result


def _cache_key(file_hash: str, mode: str) -> str:
    # Mode is part of the key so a Groq result is never served when you
    # asked for Gemini (useful when comparing the two on the same file).
    return f"{file_hash}:{mode}"


@app.post("/extract")
async def extract(
    file: UploadFile = File(...),
    mode: str = Query("groq", enum=["groq", "gemini"]),
    target: str = Query("both", enum=["ace", "netchb", "both"]),
):
    file_bytes = await file.read()
    if not file_bytes:
        raise HTTPException(status_code=400, detail="Uploaded file is empty")

    key = _cache_key(hash_file_bytes(file_bytes), mode)

    # Cache hit — skip Docling + LLM entirely, this is the whole point
    # of hashing: identical file uploaded again costs nothing.
    cached = get_cached_result(key)
    if cached and cached["status"] == "success":
        payload = cached["result"] or {}
        if payload.get("version") == EXTRACTION_VERSION and "extracted_fields" in payload:
            try:
                response = build_response(payload["extracted_fields"], target)
            except Exception as e:
                raise HTTPException(status_code=500, detail=f"Mapping failed: {e}")
            return JSONResponse({**response, "cached": True})
        # Stale version: fall through and re-extract.

    # Cache miss — run the real pipeline. Docling needs an actual file
    # on disk, not just bytes in memory, so write to a temp file first.
    suffix = os.path.splitext(file.filename or "")[1] or ".pdf"
    with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as tmp:
        tmp.write(file_bytes)
        tmp_path = tmp.name

    try:
        markdown = extract_markdown(tmp_path)

        if mode == "gemini":
            fields = extract_with_gemini(markdown)
        else:
            fields = extract_with_groq(markdown)

        # Cache the extraction only, tagged with the schema version.
        save_result(key, "success", {"version": EXTRACTION_VERSION, "extracted_fields": fields})

        response = build_response(fields, target)
        return JSONResponse({**response, "cached": False})

    except Exception as e:
        save_result(key, "failed", None)
        raise HTTPException(status_code=500, detail=f"Extraction failed: {e}")

    finally:
        os.unlink(tmp_path)