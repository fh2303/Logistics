"""
Phase 1: the same pipeline from phase0_extract.py, wrapped as a real
HTTP service instead of a CLI script — so a browser extension (or
anything else) can call it.

Run locally with:
    uvicorn api:app --reload

Then test with:
    curl -F "file=@bol2.pdf" "http://127.0.0.1:8000/extract?mode=groq&target=netchb"

Docs/interactive testing UI (auto-generated by FastAPI):
    http://127.0.0.1:8000/docs

Two ways to use it:
  * POST /extract                      one file in, mapped fields out
  * /shipments/...                     a shipment is an accumulating set of
                                       documents (they can arrive in separate
                                       emails); attach files one at a time and
                                       the merged result is recomputed each time

Caching: only the EXTRACTION (Docling + LLM, the slow/expensive part) is
cached, keyed by file hash + mode. Normalization, merging and mapping are
cheap and deterministic, so they re-run on every request. Changing a mapping
rule, a merge priority, a client answer, or the requested target takes effect
immediately, with no need to clear the cache.

All the logic lives in plain modules (database, merge, pipeline,
shipment_service) that are tested without a web server; the routes below are
thin wrappers.
"""

import tempfile
import os

from fastapi import FastAPI, UploadFile, File, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from pydantic import BaseModel

from database import (
    init_db, hash_file_bytes, get_cached_result, save_result,
    create_shipment, list_shipments, delete_shipment, get_shipment,
    delete_shipment_document,
)

# Reusing the exact functions already validated in Phase 0 — nothing
# about the extraction/normalization/mapping logic changes here.
from phase0_extract import extract_markdown, extract_with_groq, extract_with_gemini
from pipeline import build_response
from shipment_service import build_shipment_view, attach_extraction

# Bump this whenever BOL_SCHEMA or the extraction prompts change. Cached
# extractions made under an older version are ignored and re-extracted,
# instead of silently serving data that lacks the new fields.
EXTRACTION_VERSION = 2

app = FastAPI(title="BOL Extraction API")

# Allows the browser extension (a different origin: chrome-extension://...)
# to call this API. Wide open for local development — worth tightening
# before this is ever exposed beyond your own machine.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.on_event("startup")
def on_startup():
    init_db()


@app.get("/health")
def health():
    return {"status": "ok"}


def _cache_key(file_hash: str, mode: str) -> str:
    # Mode is part of the key so a Groq result is never served when you
    # asked for Gemini (useful when comparing the two on the same file).
    return f"{file_hash}:{mode}"


def extract_fields(file_bytes: bytes, filename: str | None, mode: str):
    """
    Raw extraction for one file, using the cache. Returns
    (file_hash, fields, cached). Raises HTTPException on failure.
    """
    file_hash = hash_file_bytes(file_bytes)
    key = _cache_key(file_hash, mode)

    # Cache hit — skip Docling + LLM entirely, this is the whole point
    # of hashing: identical file uploaded again costs nothing.
    cached = get_cached_result(key)
    if cached and cached["status"] == "success":
        payload = cached["result"] or {}
        if payload.get("version") == EXTRACTION_VERSION and "extracted_fields" in payload:
            return file_hash, payload["extracted_fields"], True
        # Stale version: fall through and re-extract.

    # Cache miss — run the real pipeline. Docling needs an actual file
    # on disk, not just bytes in memory, so write to a temp file first.
    suffix = os.path.splitext(filename or "")[1] or ".pdf"
    with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as tmp:
        tmp.write(file_bytes)
        tmp_path = tmp.name

    try:
        markdown = extract_markdown(tmp_path)

        if mode == "gemini":
            fields = extract_with_gemini(markdown)
        else:
            fields = extract_with_groq(markdown)

        # Cache the extraction only, tagged with the schema version.
        save_result(key, "success", {"version": EXTRACTION_VERSION, "extracted_fields": fields})
        return file_hash, fields, False

    except Exception as e:
        save_result(key, "failed", None)
        raise HTTPException(status_code=500, detail=f"Extraction failed: {e}")

    finally:
        os.unlink(tmp_path)


def _read_upload(file: UploadFile) -> bytes:
    file_bytes = file.read()
    if not file_bytes:
        raise HTTPException(status_code=400, detail="Uploaded file is empty")
    return file_bytes


# ---------------------------------------------------------------------------
# Single file
# ---------------------------------------------------------------------------

@app.post("/extract")
def extract(
    file: UploadFile = File(...),
    mode: str = Query("groq", enum=["groq", "gemini"]),
    target: str = Query("both", enum=["ace", "netchb", "both"]),
):
    file_bytes = _read_upload(file)
    _, fields, cached = extract_fields(file_bytes, file.filename, mode)
    try:
        response = build_response(fields, target)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Mapping failed: {e}")
    return JSONResponse({**response, "cached": cached})


# ---------------------------------------------------------------------------
# Shipments: documents attach over time, the merge is recomputed each time
# ---------------------------------------------------------------------------

class NewShipment(BaseModel):
    label: str


def _view_or_404(shipment_id: int, target: str) -> dict:
    view = build_shipment_view(shipment_id, target)
    if view is None:
        raise HTTPException(status_code=404, detail="Shipment not found")
    return view


@app.post("/shipments")
def new_shipment(body: NewShipment):
    label = body.label.strip()
    if not label or len(label) > 200:
        raise HTTPException(status_code=400, detail="Label must be 1-200 characters")
    shipment_id = create_shipment(label)
    return JSONResponse(_view_or_404(shipment_id, "netchb"))


@app.get("/shipments")
def shipments():
    return {"shipments": list_shipments()}


@app.get("/shipments/{shipment_id}")
def shipment(shipment_id: int, target: str = Query("netchb", enum=["ace", "netchb", "both"])):
    return JSONResponse(_view_or_404(shipment_id, target))


@app.post("/shipments/{shipment_id}/documents")
def attach_document(
    shipment_id: int,
    file: UploadFile = File(...),
    mode: str = Query("groq", enum=["groq", "gemini"]),
    target: str = Query("netchb", enum=["ace", "netchb", "both"]),
):
    if get_shipment(shipment_id) is None:
        raise HTTPException(status_code=404, detail="Shipment not found")

    file_bytes = _read_upload(file)
    file_hash, fields, cached = extract_fields(file_bytes, file.filename, mode)
    document_id, created = attach_extraction(
        shipment_id, file_hash, file.filename, mode, EXTRACTION_VERSION, fields
    )

    try:
        view = _view_or_404(shipment_id, target)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Merge/mapping failed: {e}")
    return JSONResponse({**view, "document_id": document_id, "attached": created, "cached": cached})


@app.delete("/shipments/{shipment_id}/documents/{document_id}")
def remove_document(
    shipment_id: int,
    document_id: int,
    target: str = Query("netchb", enum=["ace", "netchb", "both"]),
):
    if not delete_shipment_document(shipment_id, document_id):
        raise HTTPException(status_code=404, detail="Document not found in this shipment")
    return JSONResponse(_view_or_404(shipment_id, target))


@app.delete("/shipments/{shipment_id}")
def remove_shipment(shipment_id: int):
    if not delete_shipment(shipment_id):
        raise HTTPException(status_code=404, detail="Shipment not found")
    return {"deleted": True}